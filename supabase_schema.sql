-- 1. TABLA: PACIENTES Y TUTORES
CREATE TABLE IF NOT EXISTS public.pacientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_tutor VARCHAR(100) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    nombre_paciente VARCHAR(100) NOT NULL,
    especie VARCHAR(50) NOT NULL CHECK(especie IN ('Canino', 'Felino', 'Otro')),
    fecha_creacion TIMESTAMPTZ DEFAULT TIMEZONE('America/Bogota', NOW()) NOT NULL
);

-- 2. TABLA: OPORTUNIDADES Y SEGUIMIENTOS
CREATE TABLE IF NOT EXISTS public.oportunidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL REFERENCES public.pacientes(id) ON DELETE RESTRICT,
    fecha_registro DATE DEFAULT CURRENT_DATE NOT NULL,
    servicio_interes VARCHAR(30) NOT NULL CHECK(servicio_interes IN ('Medicina General', 'Medicina Interna')),
    tipo_oportunidad VARCHAR(50) NOT NULL CHECK(tipo_oportunidad IN (
        'Solicitud de información',
        'Cita no concretada',
        'Cancelación',
        'Inasistencia',
        'Sin nueva atención registrada'
    )),
    motivo TEXT,
    observaciones TEXT,
    fecha_propuesta_seguimiento DATE,
    estado VARCHAR(30) DEFAULT 'Pendiente' NOT NULL CHECK(estado IN (
        'Pendiente',
        'En Gestión',
        'Cita Agendada',
        'Consulta Concretada',
        'Rechazado'
    )),
    resultado_gestion TEXT,
    fecha_actualizacion TIMESTAMPTZ DEFAULT TIMEZONE('America/Bogota', NOW()) NOT NULL
);

-- 3. ÍNDICES DE RENDIMIENTO (Optimización de Filtros y KPIs)
CREATE INDEX IF NOT EXISTS idx_oportunidades_estado ON public.oportunidades(estado);
CREATE INDEX IF NOT EXISTS idx_oportunidades_seguimiento ON public.oportunidades(fecha_propuesta_seguimiento);
CREATE INDEX IF NOT EXISTS idx_oportunidades_servicio ON public.oportunidades(servicio_interes);
CREATE INDEX IF NOT EXISTS idx_oportunidades_paciente ON public.oportunidades(paciente_id);

-- 4. TRIGGER: Actualización automática de timestamp al modificar registros
CREATE OR REPLACE FUNCTION public.actualizar_fecha_modificacion()
RETURNS TRIGGER AS $$
BEGIN
    NEW.fecha_actualizacion = TIMEZONE('America/Bogota', NOW());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_actualizar_oportunidad ON public.oportunidades;
CREATE TRIGGER trigger_actualizar_oportunidad
BEFORE UPDATE ON public.oportunidades
FOR EACH ROW
EXECUTE FUNCTION public.actualizar_fecha_modificacion();

-- 5. HABILITAR ROW LEVEL SECURITY (RLS)
ALTER TABLE public.pacientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.oportunidades ENABLE ROW LEVEL SECURITY;

-- Políticas de acceso para la clave anónima (anon / public) en el Ultra-MVP
CREATE POLICY "Permitir lectura publica de pacientes" ON public.pacientes
    FOR SELECT TO anon, authenticated USING (true);

CREATE POLICY "Permitir insercion publica de pacientes" ON public.pacientes
    FOR INSERT TO anon, authenticated WITH CHECK (true);

CREATE POLICY "Permitir actualizacion publica de pacientes" ON public.pacientes
    FOR UPDATE TO anon, authenticated USING (true);

CREATE POLICY "Permitir lectura publica de oportunidades" ON public.oportunidades
    FOR SELECT TO anon, authenticated USING (true);

CREATE POLICY "Permitir insercion publica de oportunidades" ON public.oportunidades
    FOR INSERT TO anon, authenticated WITH CHECK (true);

CREATE POLICY "Permitir actualizacion publica de oportunidades" ON public.oportunidades
    FOR UPDATE TO anon, authenticated USING (true);

-- 6. VISTA OFICIAL DE LOS 7 KPIS PARA EL PLAN DE MEJORAMIENTO (GRADO MVZ)
CREATE OR REPLACE VIEW public.vista_metricas_dashboard AS
SELECT
    COUNT(*) AS total_identificadas,
    COUNT(*) FILTER (WHERE estado != 'Pendiente') AS total_gestionadas,
    COUNT(*) FILTER (WHERE estado = 'Cita Agendada') AS citas_generadas,
    COUNT(*) FILTER (WHERE estado = 'Consulta Concretada') AS consultas_concretadas,
    COUNT(*) FILTER (
        WHERE estado = 'Consulta Concretada' 
        AND tipo_oportunidad IN ('Inasistencia', 'Cancelación', 'Sin nueva atención registrada')
    ) AS pacientes_recuperados,
    COUNT(*) FILTER (WHERE estado = 'Consulta Concretada' AND servicio_interes = 'Medicina General') AS consultas_general,
    COUNT(*) FILTER (WHERE estado = 'Consulta Concretada' AND servicio_interes = 'Medicina Interna') AS consultas_interna
FROM public.oportunidades;
