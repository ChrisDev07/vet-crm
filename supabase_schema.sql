-- 6. VISTA OFICIAL DE LOS KPIS PARA EL PLAN DE MEJORAMIENTO (GRADO MVZ)
DROP VIEW IF EXISTS public.vista_metricas_dashboard CASCADE;
CREATE OR REPLACE VIEW public.vista_metricas_dashboard
WITH (security_invoker = true) AS
SELECT
    COUNT(*) AS total_identificadas,
    COUNT(*) FILTER (WHERE estado != 'Pendiente') AS total_gestionadas,
    COUNT(*) FILTER (WHERE estado = 'Cita Agendada') AS citas_generadas,
    COUNT(*) FILTER (WHERE estado = 'Consulta Concretada') AS consultas_concretadas,
    COUNT(*) FILTER (
        WHERE estado = 'Consulta Concretada' 
        AND tipo_oportunidad IN ('Inasistencia', 'Cancelación', 'Sin nueva atención registrada')
    ) AS pacientes_recuperados,
    COUNT(*) FILTER (WHERE estado = 'Consulta Concretada' AND servicio_interes = 'Medicina General') AS consultas_general,
    COUNT(*) FILTER (WHERE estado = 'Consulta Concretada' AND servicio_interes = 'Medicina Interna') AS consultas_interna,
    COUNT(*) FILTER (WHERE estado = 'Consulta Concretada' AND servicio_interes = 'Vacunación & Desparasitación') AS consultas_vacunacion,
    COUNT(*) FILTER (WHERE estado = 'Consulta Concretada' AND servicio_interes = 'Cirugía/Quirófano') AS consultas_cirugia
FROM public.oportunidades;

REVOKE ALL ON public.vista_metricas_dashboard FROM PUBLIC;
REVOKE ALL ON public.vista_metricas_dashboard FROM anon;
GRANT SELECT ON public.vista_metricas_dashboard TO authenticated;
